export const MAX_RESOURCE_BYTES = 25 * 1024 * 1024;
export const CLASS_STORAGE_BYTES = 100 * 1024 * 1024;

export interface ResourceLimits {
  documentBytes: number;
  videoBytes: number;
  fileBytes: number;
  classBytes: number;
}

export function loadResourceLimits(env: NodeJS.ProcessEnv = process.env): ResourceLimits {
  const mib = (name: string, fallback: number, ceiling: number) => {
    const value = Number(env[name] || fallback);
    if (!Number.isSafeInteger(value) || value < 1 || value > ceiling)
      throw new Error(`${name} must be a whole MiB value from 1 to ${ceiling}.`);
    return value * 1024 * 1024;
  };
  const documentBytes = mib('RESOURCE_MAX_DOCUMENT_MIB', 25, 100);
  const videoBytes = mib('RESOURCE_MAX_VIDEO_MIB', 100, 500);
  return {
    documentBytes,
    videoBytes,
    fileBytes: Math.max(documentBytes, videoBytes),
    classBytes: mib('CLASS_STORAGE_MIB', 500, 102400),
  };
}

export interface StorageConfig {
  driver: 'local' | 'r2';
  localDirectory: string;
  r2?: { accountId: string; bucket: string; accessKeyId: string; secretAccessKey: string };
}

export interface StoragePutContext {
  userId: string;
  filename?: string;
}

export interface PrivateStorage {
  putFile(
    key: string,
    path: string,
    contentType: string,
    context?: StoragePutContext,
  ): Promise<void>;
  open(key: string): Promise<{ stream: Readable; size: number; contentType?: string }>;
  delete(key: string): Promise<void>;
  close?(): void | Promise<void>;
}

export function loadStorageConfig(env: NodeJS.ProcessEnv = process.env): StorageConfig {
  const driver = env.STORAGE_DRIVER || 'local';
  if (driver !== 'local' && driver !== 'r2') throw new Error('STORAGE_DRIVER must be local or r2.');
  const config: StorageConfig = {
    driver,
    localDirectory: resolve(env.STORAGE_LOCAL_DIR || 'data/storage'),
  };
  if (driver === 'r2') {
    const { R2_ACCOUNT_ID, R2_BUCKET, R2_ACCESS_KEY_ID, R2_SECRET_ACCESS_KEY } = env;
    if (
      !R2_ACCOUNT_ID ||
      !/^[a-f0-9]{32}$/i.test(R2_ACCOUNT_ID) ||
      !R2_BUCKET ||
      !/^[a-z0-9][a-z0-9.-]{1,61}[a-z0-9]$/.test(R2_BUCKET) ||
      !R2_ACCESS_KEY_ID ||
      !R2_SECRET_ACCESS_KEY
    )
      throw new Error(
        'R2 storage requires a valid R2_ACCOUNT_ID, R2_BUCKET, R2_ACCESS_KEY_ID and R2_SECRET_ACCESS_KEY.',
      );
    config.r2 = {
      accountId: R2_ACCOUNT_ID,
      bucket: R2_BUCKET,
      accessKeyId: R2_ACCESS_KEY_ID,
      secretAccessKey: R2_SECRET_ACCESS_KEY,
    };
  }
  return config;
}

function checkKey(key: string): void {
  // Keys are generated by the server. Never accept a filename or URL as a storage key.
  if (!/^(resources|avatars)\/[a-f0-9-]{36}(?:\.[a-z0-9]{1,8})?$/.test(key))
    throw new Error('Invalid private storage key.');
}

export function createPrivateStorage(config: StorageConfig = loadStorageConfig()): PrivateStorage {
  if (config.driver === 'local') {
    const root = resolve(config.localDirectory);
    // Misconfiguration must never make upload bytes a public static asset.
    const publicRoots = [resolve('client/public'), resolve('dist/client')];
    if (publicRoots.some((publicRoot) => root === publicRoot || root.startsWith(publicRoot + sep)))
      throw new Error('Private storage must be outside the web asset directories.');
    const pathFor = (key: string) => {
      checkKey(key);
      const path = resolve(root, key);
      if (!path.startsWith(root + sep)) throw new Error('Invalid private storage path.');
      return path;
    };
    return {
      async putFile(key, sourcePath) {
        const path = pathFor(key);
        await mkdir(dirname(path), { recursive: true, mode: 0o700 });
        await copyFile(sourcePath, path);
      },
      async open(key) {
        const path = pathFor(key);
        try {
          const info = await stat(path);
          requireCondition(
            info.isFile(),
            404,
            'file_unavailable',
            'This file is temporarily unavailable.',
          );
          return { stream: createReadStream(path), size: info.size };
        } catch (error) {
          if ((error as NodeJS.ErrnoException).code === 'ENOENT')
            throw new ApiError(404, 'file_unavailable', 'This file is temporarily unavailable.');
          throw error;
        }
      },
      async delete(key) {
        await rm(pathFor(key), { force: true });
      },
    };
  }
  const r2 = config.r2;
  if (!r2) throw new Error('R2 storage credentials are required.');
  const s3 = new S3Client({
    region: 'auto',
    endpoint: `https://${r2.accountId}.r2.cloudflarestorage.com`,
    credentials: { accessKeyId: r2.accessKeyId, secretAccessKey: r2.secretAccessKey },
    requestChecksumCalculation: 'WHEN_REQUIRED',
    responseChecksumValidation: 'WHEN_REQUIRED',
    maxAttempts: 2,
  });
  return {
    async putFile(key, path, contentType) {
      checkKey(key);
      const info = await stat(path);
      const body = createReadStream(path);
      try {
        await s3.send(
          new PutObjectCommand({
            Bucket: r2.bucket,
            Key: key,
            Body: body,
            ContentType: contentType,
            ContentLength: info.size,
            CacheControl: 'private, no-store',
          }),
          { abortSignal: AbortSignal.timeout(60_000) },
        );
      } finally {
        body.destroy();
      }
    },
    async open(key) {
      checkKey(key);
      try {
        const value = await s3.send(new GetObjectCommand({ Bucket: r2.bucket, Key: key }), {
          abortSignal: AbortSignal.timeout(60_000),
        });
        if (!(value.Body instanceof Readable)) throw new Error('R2 returned no readable object.');
        return {
          stream: value.Body,
          size: value.ContentLength || 0,
          contentType: value.ContentType,
        };
      } catch (error) {
        if ((error as { name?: string }).name === 'NoSuchKey')
          throw new ApiError(404, 'file_unavailable', 'This file is temporarily unavailable.');
        throw error;
      }
    },
    async delete(key) {
      checkKey(key);
      await s3.send(new DeleteObjectCommand({ Bucket: r2.bucket, Key: key }), {
        abortSignal: AbortSignal.timeout(30_000),
      });
    },
    close() {
      s3.destroy();
    },
  };
}

export interface TemporaryUpload {
  path: string;
  filename: string;
  mime: string;
  fields: Record<string, string>;
  size: number;
  cleanup(): Promise<void>;
}

/** Bounded disk spool: never aggregate lecture uploads into an in-memory Buffer. */
export async function temporaryUpload(
  request: FastifyRequest,
  maxBytes = MAX_RESOURCE_BYTES,
): Promise<TemporaryUpload> {
  requireCondition(request.isMultipart(), 415, 'multipart_required', 'Choose a file to upload.');
  const tempRoot = resolve(process.env.UPLOAD_TEMP_DIR || 'data/tmp');
  requireCondition(
    ![resolve('client/public'), resolve('dist/client')].some(
      (root) => tempRoot === root || tempRoot.startsWith(root + sep),
    ),
    503,
    'storage_configuration',
    'Private upload storage is not configured correctly.',
  );
  await mkdir(tempRoot, { recursive: true, mode: 0o700 });
  const directory = await mkdtemp(resolve(tempRoot, 'upload-'));
  const path = resolve(directory, 'body');
  const cleanup = () => rm(directory, { recursive: true, force: true });
  const fields: Record<string, string> = Object.create(null);
  let filename = '',
    mime = '',
    size = 0,
    hasFile = false;
  try {
    for await (const part of request.parts({
      limits: {
        files: 1,
        fileSize: maxBytes,
        fields: 8,
        fieldSize: 12000,
        fieldNameSize: 60,
        parts: 9,
        headerPairs: 64,
      },
    })) {
      if (part.type === 'file') {
        requireCondition(
          !hasFile && part.fieldname === 'file',
          400,
          'invalid_file',
          'Upload exactly one file in the file field.',
        );
        hasFile = true;
        filename = safeFilename(part.filename);
        mime = part.mimetype;
        await pipeline(
          part.file,
          new Transform({
            transform(chunk: Buffer, _encoding, callback) {
              size += chunk.length;
              callback(
                size > maxBytes
                  ? new ApiError(413, 'file_too_large', 'This file exceeds the upload limit.')
                  : null,
                chunk,
              );
            },
          }),
          createWriteStream(path, { flags: 'wx', mode: 0o600 }),
        );
        requireCondition(
          !part.file.truncated,
          413,
          'file_too_large',
          'This file exceeds the upload limit.',
        );
      } else {
        requireCondition(
          !part.valueTruncated &&
            !part.fieldnameTruncated &&
            typeof part.value === 'string' &&
            !Object.hasOwn(fields, part.fieldname),
          400,
          'invalid_upload_fields',
          'Upload fields are invalid or too long.',
        );
        fields[part.fieldname] = part.value;
      }
    }
    requireCondition(hasFile && size > 0, 400, 'file_required', 'Choose a non-empty file.');
    return { path, filename, mime, fields, size, cleanup };
  } catch (error) {
    await cleanup();
    throw error;
  }
}

export function safeFilename(value: string): string {
  const name = value
    .normalize('NFKC')
    .replace(/[\\/]/g, '_')
    .replace(/[\u0000-\u001f\u007f]/g, '')
    .trim();
  return name.slice(-180) || 'document';
}

export function attachmentDisposition(filename: string): string {
  const clean = safeFilename(filename);
  const ascii = clean.replace(/[^a-zA-Z0-9._ -]/g, '_').replace(/["\\]/g, '_');
  return `attachment; filename="${ascii}"; filename*=UTF-8''${encodeURIComponent(clean).replace(/['()*]/g, (c) => `%${c.charCodeAt(0).toString(16).toUpperCase()}`)}`;
}

async function packageXml(zip: ZipFile, entry: Entry): Promise<string> {
  requireCondition(
    entry.uncompressedSize <= 2 * 1024 * 1024,
    400,
    'invalid_file_type',
    'PowerPoint metadata is too large.',
  );
  const stream = await new Promise<Readable>((resolveStream, reject) =>
    zip.openReadStream(entry, (error, value) => {
      if (error || !value) reject(error || new Error('Missing ZIP entry'));
      else resolveStream(value);
    }),
  );
  const chunks: Buffer[] = [];
  let size = 0;
  for await (const chunk of stream) {
    size += chunk.length;
    requireCondition(
      size <= 2 * 1024 * 1024,
      400,
      'invalid_file_type',
      'PowerPoint metadata is too large.',
    );
    chunks.push(Buffer.from(chunk));
  }
  const xml = Buffer.concat(chunks).toString('utf8');
  // We inspect text only. Never resolve XML entities or load external relationships.
  requireCondition(
    !/<!DOCTYPE|<!ENTITY/i.test(xml),
    400,
    'invalid_file_type',
    'Unsupported PowerPoint metadata.',
  );
  return xml;
}

async function inspectOfficePackage(path: string, kind: 'pptx' | 'docx'): Promise<void> {
  const label = kind === 'pptx' ? 'PowerPoint' : 'Word';
  const mainPath = kind === 'pptx' ? 'ppt/presentation.xml' : 'word/document.xml';
  const mainType =
    kind === 'pptx'
      ? 'application/vnd.openxmlformats-officedocument.presentationml.presentation.main+xml'
      : 'application/vnd.openxmlformats-officedocument.wordprocessingml.document.main+xml';
  return new Promise((resolvePromise, reject) => {
    openZip(
      path,
      { lazyEntries: true, validateEntrySizes: true, strictFileNames: true, autoClose: true },
      (error, zip) => {
        if (error || !zip) {
          reject(new ApiError(400, 'invalid_file_type', `This is not a valid ${label} package.`));
          return;
        }
        let count = 0,
          expandedBytes = 0,
          hasContentTypes = false,
          hasPresentation = false,
          settled = false;
        const names = new Set<string>();
        const fail = () => {
          if (settled) return;
          settled = true;
          zip.close();
          reject(
            new ApiError(
              400,
              'invalid_file_type',
              `This ${label} package is unsupported or unsafe.`,
            ),
          );
        };
        zip.on('error', fail);
        zip.on('entry', (entry: Entry) => {
          if (settled) return;
          count++;
          expandedBytes += entry.uncompressedSize;
          const name = entry.fileName.toLowerCase();
          if (
            count > 4000 ||
            expandedBytes > 200 * 1024 * 1024 ||
            entry.uncompressedSize > 50 * 1024 * 1024 ||
            names.has(name) ||
            (entry.generalPurposeBitFlag & 1) !== 0 ||
            ![0, 8].includes(entry.compressionMethod) ||
            /(?:vbaproject\.bin|\.exe$|\.js$|\.html?$|\.svg$|\.bat$|\.cmd$|\.ps1$|\.zip$|\.rar$|\.7z$)/i.test(
              name,
            ) ||
            name.startsWith('ppt/embeddings/') ||
            name.startsWith('word/embeddings/') ||
            name.includes('activex')
          ) {
            fail();
            return;
          }
          names.add(name);
          if (name === '[content_types].xml' || name === mainPath) {
            void packageXml(zip, entry)
              .then((xml) => {
                if (settled) return;
                if (name === '[content_types].xml') {
                  hasContentTypes =
                    /<(?:[A-Za-z][\w.-]*:)?Types\b/.test(xml) &&
                    xml.includes(mainType) &&
                    !/macroEnabled|vbaProject|activeX/i.test(xml);
                } else {
                  hasPresentation =
                    kind === 'pptx'
                      ? /<(?:[A-Za-z][\w.-]*:)?presentation\b/.test(xml) &&
                        (xml.includes(
                          'http://schemas.openxmlformats.org/presentationml/2006/main',
                        ) ||
                          xml.includes('http://purl.oclc.org/ooxml/presentationml/main'))
                      : /<(?:[A-Za-z][\w.-]*:)?document\b/.test(xml) &&
                        (xml.includes(
                          'http://schemas.openxmlformats.org/wordprocessingml/2006/main',
                        ) ||
                          xml.includes('http://purl.oclc.org/ooxml/wordprocessingml/main'));
                }
                zip.readEntry();
              })
              .catch(fail);
          } else zip.readEntry();
        });
        zip.on('end', () => {
          if (settled) return;
          if (hasContentTypes && hasPresentation) {
            settled = true;
            resolvePromise();
          } else fail();
        });
        zip.readEntry();
      },
    );
  });
}

export async function validateResourceFile(
  upload: Pick<TemporaryUpload, 'path' | 'filename' | 'size'>,
  limits: ResourceLimits = loadResourceLimits({}),
): Promise<string> {
  const extension = extname(upload.filename).toLowerCase();
  requireCondition(
    ['.pdf', '.ppt', '.pptx', '.doc', '.docx', '.mp4', '.webm'].includes(extension),
    415,
    'unsupported_file_type',
    'Upload a PDF, PPT, PPTX, DOC, DOCX, MP4 or WebM resource.',
  );
  requireCondition(
    upload.size > 0 &&
      upload.size <=
        (['.mp4', '.webm'].includes(extension) ? limits.videoBytes : limits.documentBytes),
    413,
    'file_too_large',
    'This file exceeds the configured document or video upload limit.',
  );
  const handle = await openFile(upload.path, 'r');
  const head = Buffer.alloc(16);
  let tail: Buffer;
  try {
    await handle.read(head, 0, head.length, 0);
    tail = Buffer.alloc(Math.min(upload.size, 2048));
    await handle.read(tail, 0, tail.length, Math.max(0, upload.size - tail.length));
  } finally {
    await handle.close();
  }
  if (extension === '.pdf') {
    requireCondition(
      /^%PDF-[12]\.[0-9]/.test(head.toString('ascii')) && tail.includes(Buffer.from('%%EOF')),
      400,
      'invalid_file_type',
      'This file does not look like a complete PDF.',
    );
    return 'application/pdf';
  }
  if (extension === '.mp4') {
    await inspectMp4(upload.path, upload.size);
    return 'video/mp4';
  }
  if (extension === '.webm') {
    await inspectWebM(upload.path, upload.size);
    return 'video/webm';
  }
  if (extension === '.ppt' || extension === '.doc') {
    requireCondition(
      upload.size >= 512 && head.subarray(0, 8).equals(Buffer.from('d0cf11e0a1b11ae1', 'hex')),
      400,
      'invalid_file_type',
      'This file does not look like a legacy Office document.',
    );
    return extension === '.ppt' ? 'application/vnd.ms-powerpoint' : 'application/msword';
  }
  requireCondition(
    head.subarray(0, 4).equals(Buffer.from('504b0304', 'hex')),
    400,
    'invalid_file_type',
    'This file does not look like an Office document package.',
  );
  await inspectOfficePackage(upload.path, extension === '.pptx' ? 'pptx' : 'docx');
  return extension === '.pptx'
    ? 'application/vnd.openxmlformats-officedocument.presentationml.presentation'
    : 'application/vnd.openxmlformats-officedocument.wordprocessingml.document';
}

/** Structural container checks only: uploaded media is always an attachment, never executable web content. */
async function inspectMp4(path: string, size: number): Promise<void> {
  const handle = await openFile(path, 'r');
  let position = 0,
    boxes = 0,
    ftyp = false,
    moov = false,
    mdat = false;
  const fail = () =>
    new ApiError(400, 'invalid_file_type', 'This file does not look like a complete MP4 video.');
  try {
    while (position < size) {
      if (++boxes > 100_000 || position + 8 > size) throw fail();
      const head = Buffer.alloc(16);
      const read = await handle.read(head, 0, Math.min(16, size - position), position);
      if (read.bytesRead < 8) throw fail();
      let length = head.readUInt32BE(0),
        header = 8;
      if (length === 1) {
        if (read.bytesRead < 16) throw fail();
        const large = head.readBigUInt64BE(8);
        if (large > BigInt(Number.MAX_SAFE_INTEGER)) throw fail();
        length = Number(large);
        header = 16;
      } else if (length === 0) length = size - position;
      if (length < header || position + length > size) throw fail();
      const type = head.toString('ascii', 4, 8);
      if (type === 'ftyp') {
        if (position !== 0 || length < 16 || length > 4096) throw fail();
        const brands = Buffer.alloc(length - 8);
        await handle.read(brands, 0, brands.length, position + 8);
        ftyp = /isom|iso[2-9]|mp4[12]|avc1|M4V |dash/.test(brands.toString('ascii'));
      }
      if (type === 'moov' && length > header) moov = true;
      if (type === 'mdat' && length > header) mdat = true;
      position += length;
    }
    if (!ftyp || !moov || !mdat) throw fail();
  } finally {
    await handle.close();
  }
}

async function inspectWebM(path: string, size: number): Promise<void> {
  const handle = await openFile(path, 'r'),
    head = Buffer.alloc(Math.min(size, 4096));
  try {
    await handle.read(head, 0, head.length, 0);
  } finally {
    await handle.close();
  }
  const fail = () =>
    new ApiError(400, 'invalid_file_type', 'This file does not look like a WebM video.');
  if (head.length < 16 || !head.subarray(0, 4).equals(Buffer.from('1a45dfa3', 'hex'))) throw fail();
  function vint(offset: number, keepMarker = false): { length: number; value: number } {
    const first = head[offset];
    if (!first) throw fail();
    let length = 1,
      marker = 0x80;
    while (!(first & marker) && length <= 8) {
      marker >>= 1;
      length++;
    }
    if (length > 8 || offset + length > head.length) throw fail();
    let value = keepMarker ? first : first & (marker - 1);
    for (let i = 1; i < length; i++) value = value * 256 + head[offset + i]!;
    if (!Number.isSafeInteger(value)) throw fail();
    return { length, value };
  }
  const length = vint(4),
    end = 4 + length.length + length.value;
  if (end + 4 > head.length) throw fail();
  let position = 4 + length.length,
    webm = false;
  while (position < end) {
    const id = vint(position, true);
    position += id.length;
    const len = vint(position);
    position += len.length;
    if (position + len.value > end) throw fail();
    if (id.value === 0x4282)
      webm = head.toString('ascii', position, position + len.value) === 'webm';
    position += len.value;
  }
  if (!webm || !head.subarray(end, end + 4).equals(Buffer.from('18538067', 'hex'))) throw fail();
}
